"""REST API + minimal web UI.

    GET  /health   liveness: the process is up (no dependencies checked)
    GET  /ready    readiness: index loaded and, for the LLM backend, Ollama reachable (503 otherwise)
    POST /ask      full RAG answer with sources (saved to the answer history)
    POST /search   retrieval only (debugging the search)
    GET  /history  latest answers with their ratings; GET /history/summary - per model/prompt
    POST /history/{answer_id}/rating   manual rating: score 1-5, flags, comment
    GET  /config   active pipeline configuration (no secrets) and index statistics
    GET  /docs     Swagger UI (generated by FastAPI)
    GET  /         small HTML page to ask questions

Liveness and readiness are separate on purpose: in labs 2-3 a container orchestrator restarts
a service that fails /health but only stops sending traffic to one that fails /ready.
Every response carries X-Request-ID; the same id is in every log line of that request.
Errors are returned as {"error": ..., "request_id": ...} without stack traces.
"""
from __future__ import annotations

import logging
import threading
import json
import os
import time
import uuid
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import HTMLResponse, JSONResponse
from pydantic import BaseModel, Field

from common.config import Settings, load_pipeline_config
from common.logging_setup import log_event, request_id_var, setup_logging
from history.store import AnswerHistory, HistoryError

log = logging.getLogger("api")

SERVICE = "rag-lab1"
VERSION = "1.0.0"


class AskRequest(BaseModel):
    question: str = Field(..., min_length=1, max_length=1000, examples=["How do I enable wave transfers?"])
    debug: bool = Field(False, description="include retrieved/dropped/reranked chunks")


class SearchRequest(BaseModel):
    query: str = Field(..., min_length=1, max_length=1000, examples=["removal strategy FEFO"])
    top_k: Optional[int] = Field(None, ge=1, le=100)


class Source(BaseModel):
    n: int
    cited: bool
    title: str
    section: str
    url: str
    doc_id: str
    chunk_id: str
    score: float


class AskResponse(BaseModel):
    query: str
    answer: str
    refused: bool
    refusal_reason: Optional[str]
    language: str
    sources: list[Source]
    model: str
    timings_ms: dict
    answer_id: Optional[str] = Field(None, description="id for POST /history/{answer_id}/rating")
    debug: Optional[dict] = None


class RatingRequest(BaseModel):
    score: int = Field(..., ge=1, le=5, description="1 = useless or wrong, 5 = correct and complete")
    flags: list[str] = Field(default_factory=list, examples=[["incomplete"]])
    comment: str = Field("", max_length=1000)
    rater: str = Field("", max_length=100)


class State:
    """Pipeline is loaded in a background thread so /health answers immediately."""

    def __init__(self) -> None:
        self.settings = Settings.from_env()
        self.pipeline = None
        self.history = AnswerHistory(self.settings.history_dir) if self.settings.history_enabled else None
        self.error: Optional[str] = None
        self.loading = False

    def load(self) -> None:
        self.loading = True
        try:
            from pipeline.rag import RagPipeline

            config = load_pipeline_config(self.settings.config_path, self.settings)
            if os.environ.get("RAG_OVERRIDES"):  # set by `run.py serve --set ...`
                config = config.with_overrides(json.loads(os.environ["RAG_OVERRIDES"]))
            start = time.perf_counter()
            self.pipeline = RagPipeline.from_config(self.settings, config)
            log_event(log, "pipeline ready", index=self.pipeline.index.key, chunks=len(self.pipeline.index.chunks),
                      seconds=round(time.perf_counter() - start, 2))
        except Exception as exc:  # noqa: BLE001 - reported by /ready
            self.error = f"{type(exc).__name__}: {exc}"
            log.error("pipeline failed to load: %s", self.error)
        finally:
            self.loading = False


state = State()


@asynccontextmanager
async def lifespan(app: FastAPI):
    setup_logging(state.settings.log_level, state.settings.log_format)
    threading.Thread(target=state.load, name="pipeline-loader", daemon=True).start()
    yield


app = FastAPI(
    title="Odoo Inventory RAG",
    version=VERSION,
    description="Question answering over the Odoo 18 Inventory and Barcode documentation (PAD lab 1).",
    lifespan=lifespan,
)


@app.middleware("http")
async def request_context(request: Request, call_next):
    rid = request.headers.get("X-Request-ID") or uuid.uuid4().hex[:12]
    token = request_id_var.set(rid)
    start = time.perf_counter()
    try:
        response = await call_next(request)
    except Exception:  # noqa: BLE001 - last resort, endpoints handle their own errors
        log.exception("unhandled error")
        response = JSONResponse({"error": "internal error", "request_id": rid}, status_code=500)
    ms = (time.perf_counter() - start) * 1000
    response.headers["X-Request-ID"] = rid
    if request.url.path not in ("/health",):
        log_event(log, "request", method=request.method, path=request.url.path, status=response.status_code, ms=round(ms, 1))
    request_id_var.reset(token)
    return response


def _error(status: int, message: str) -> JSONResponse:
    return JSONResponse({"error": message, "request_id": request_id_var.get()}, status_code=status)


def _pipeline_or_error():
    if state.pipeline is not None:
        return state.pipeline, None
    if state.error:
        return None, _error(503, f"pipeline is not available: {state.error}")
    return None, _error(503, "pipeline is still loading, retry in a few seconds")


@app.get("/health", tags=["service"])
def health():
    return {"status": "ok", "service": SERVICE, "version": VERSION}


@app.get("/ready", tags=["service"])
def ready():
    checks: dict = {}
    ok = True
    p = state.pipeline
    if p is None:
        ok = False
        checks["index"] = {"ok": False, "detail": state.error or "loading"}
    else:
        checks["index"] = {"ok": True, "detail": f"{p.index.key}: {len(p.index.chunks)} chunks"}
        if p.config.generation.backend == "ollama" or p.config.retrieval.translate_query or p.config.embedding.backend == "ollama":
            from generation.ollama_client import OllamaClient

            up, info = OllamaClient(state.settings).health()
            checks["ollama"] = {"ok": up, "detail": info, "url": state.settings.ollama_url}
            ok = ok and up
    body = {"status": "ready" if ok else "not_ready", "checks": checks}
    return JSONResponse(body, status_code=200 if ok else 503)


@app.post("/ask", response_model=AskResponse, response_model_exclude_none=True, tags=["rag"],
          responses={422: {"description": "invalid question"}, 503: {"description": "pipeline, reranker or LLM unavailable"}})
def ask(req: AskRequest):
    from generation.ollama_client import OllamaError
    from pipeline.rag import QueryError
    from reranking.rerankers import RerankError

    pipeline, err = _pipeline_or_error()
    if err:
        return err
    try:
        ans = pipeline.answer(req.question)
    except QueryError as exc:
        return _error(422, str(exc))
    except OllamaError as exc:
        log.warning("LLM error: %s", exc)
        return _error(503, f"LLM unavailable: {exc}")
    except RerankError as exc:
        log.warning("reranker error: %s", exc)
        return _error(503, f"reranker unavailable: {exc}")
    except Exception:  # noqa: BLE001
        log.exception("ask failed")
        return _error(500, "internal error")
    data = ans.to_dict(debug=req.debug)
    if state.history is not None:
        try:
            data["answer_id"] = state.history.add_answer(_history_record(pipeline, data))
        except Exception as exc:  # noqa: BLE001 - a full disk or a broken record must not break answering
            log.warning("history not saved: %s: %s", type(exc).__name__, exc)
    log_event(log, "answer", refused=ans.refused, reason=ans.refusal_reason, sources=len(ans.sources),
              model=ans.model, total_ms=round(ans.timings_ms.get("total", 0), 1))
    return data


def _history_record(pipeline, data: dict) -> dict:
    cfg = pipeline.config
    return {
        "source": "api",
        "request_id": request_id_var.get(),
        "question": data["query"],
        "language": data["language"],
        "answer": data["answer"],
        "refused": data["refused"],
        "refusal_reason": data["refusal_reason"],
        "model": data["model"],
        "prompt": cfg.generation.prompt,
        "config_fingerprint": cfg.fingerprint(),
        "index": pipeline.index.key,
        "sources": [{k: s[k] for k in ("n", "cited", "doc_id", "chunk_id", "url")} for s in data["sources"]],
        "timings_ms": data["timings_ms"],
    }


def _history_or_error():
    if state.history is None:
        return None, _error(404, "answer history is disabled (HISTORY_ENABLED=false)")
    return state.history, None


@app.get("/history", tags=["history"])
def history(limit: int = 20):
    h, err = _history_or_error()
    if err:
        return err
    return {"answers": h.recent(max(1, min(limit, 200)))}


@app.get("/history/summary", tags=["history"])
def history_summary():
    h, err = _history_or_error()
    if err:
        return err
    return h.summary()


@app.post("/history/{answer_id}/rating", tags=["history"])
def rate_answer(answer_id: str, req: RatingRequest):
    h, err = _history_or_error()
    if err:
        return err
    try:
        rating = h.rate(answer_id, req.score, req.flags, req.comment, req.rater)
    except HistoryError as exc:
        return _error(404 if "not found" in str(exc) else 422, str(exc))
    log_event(log, "rating", answer_id=answer_id, score=req.score, flags=",".join(rating["flags"]))
    return rating


@app.post("/search", tags=["rag"])
def search(req: SearchRequest):
    from pipeline.rag import QueryError
    from reranking.rerankers import RerankError

    pipeline, err = _pipeline_or_error()
    if err:
        return err
    try:
        r = pipeline.retrieve(req.query, top_k=req.top_k)
    except QueryError as exc:
        return _error(422, str(exc))
    except RerankError as exc:
        log.warning("reranker error: %s", exc)
        return _error(503, f"reranker unavailable: {exc}")
    except Exception:  # noqa: BLE001
        log.exception("search failed")
        return _error(500, "internal error")
    return {
        "query": r.query,
        "search_query": r.search_query,
        "language": r.language,
        "results": [c.to_dict(with_text=True) for c in r.reranked],
        "retrieved": [c.to_dict(with_text=False) for c in r.retrieved],
        "dropped": r.dropped,
        "timings_ms": {k: round(v, 1) for k, v in r.timings_ms.items()},
    }


@app.get("/config", tags=["service"])
def config():
    pipeline, err = _pipeline_or_error()
    if err:
        return err
    s = state.settings
    return {
        "pipeline": pipeline.config.model_dump(exclude={"source"}),
        "index": {k: v for k, v in pipeline.index.meta.items() if k != "config"},
        "models": {"llm": s.llm_model, "embed": s.embed_model, "rerank": s.rerank_model},
        "ollama_url": s.ollama_url,
    }


@app.exception_handler(RequestValidationError)
async def invalid_request(request: Request, exc: RequestValidationError):
    problems = "; ".join(f"{'.'.join(str(p) for p in e['loc'][1:])}: {e['msg']}" for e in exc.errors())
    return _error(422, f"invalid request: {problems}")


@app.exception_handler(Exception)
async def unhandled(request: Request, exc: Exception):
    log.exception("unhandled error")
    return _error(500, "internal error")


