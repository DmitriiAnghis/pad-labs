"""experiments/REPORT.md from experiments/results/*.json (python run.py report).

The report only shows numbers; the reasoning ("why this variant was chosen") lives in
DECISIONS.md, written by a person after reading the numbers.
"""
from __future__ import annotations

from pathlib import Path

from common.config import LAB_ROOT, Settings
from common.utils import read_json, utc_now
from evaluation.experiments import RESULTS_DIR, load_experiments

REPORT = LAB_ROOT / "experiments" / "REPORT.md"

RETRIEVAL_COLS = [
    ("MRR [95% CI]", lambda s: f"{s['final']['mrr']:.3f} [{s['final_ci95']['mrr'][0]:.2f}-{s['final_ci95']['mrr'][1]:.2f}]" if s.get("final_ci95") else s["final"]["mrr"]),
    ("Hit@1", lambda s: s["final"]["hit@1"]),
    ("Hit@5", lambda s: s["final"]["hit@5"]),
    ("Recall@5", lambda s: s["final"]["recall@5"]),
    ("nDCG@5", lambda s: s["final"]["ndcg@5"]),
    ("Evidence@5", lambda s: s["final"]["evidence@5"]),
    ("Evidence@ctx", lambda s: s["final"].get("evidence@ctx")),
    ("context chars", lambda s: round(s["context_chars"]) if s.get("context_chars") is not None else None),
    ("Recall@20 (retriever)", lambda s: s["retriever"]["recall@20"]),
    ("no context: answerable / no-answer", lambda s: f"{_n(s['refusal']['answerable_without_context'])} / {_n(s['refusal']['no_answer_without_context'])}"),
    ("p50 ms", lambda s: s["latency_ms"]["p50"]),
]

GENERATION_COLS = [
    ("behaviour acc.", lambda s: s["behaviour_accuracy"]),
    ("no-answer refused", lambda s: s["no_answer_refused"]),
    ("false refusals", lambda s: s["false_refusals"]),
    ("keyword cov.", lambda s: s["keyword_coverage"]),
    ("citation rate", lambda s: s["citation_rate"]),
    ("citation precision", lambda s: s["citation_precision"]),
    ("judge correct", lambda s: s.get("judge_correct")),
    ("judge faithful", lambda s: s.get("judge_faithful")),
    ("p50 ms", lambda s: s["latency_ms"]["p50"]),
]


def _n(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def _table(data: dict) -> list[str]:
    cols = RETRIEVAL_COLS if data["kind"] == "retrieval" else GENERATION_COLS
    extra = ["chunks"] if data["kind"] == "retrieval" else ["model"]
    header = ["variant", "lang"] + [c for c, _ in cols] + extra
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for row in data["rows"]:
        if "summary" not in row:
            status = f"skipped: {row['skipped']}" if "skipped" in row else f"error: {row.get('error', '?')[:120]}"
            lines.append(f"| {row['variant']} | {row['lang']} | {status} |" + " |" * (len(header) - 3))
            continue
        s = row["summary"]
        cells = []
        for _, fn in cols:
            try:
                cells.append(_n(fn(s)))
            except (KeyError, TypeError):
                cells.append("-")
        if data["kind"] == "retrieval":
            cells.append(_n((row.get("index") or {}).get("chunks")))
        else:
            cells.append(str(row["overrides"].get("generation.model") or row["overrides"].get("generation.backend") or "default"))
        lines.append(f"| {row['variant']} | {row['lang']} | " + " | ".join(cells) + " |")
    return lines


def _best(data: dict) -> str | None:
    focus = data.get("focus")
    rows = [r for r in data["rows"] if "summary" in r]
    if not rows or not focus or focus in ("latency", "refusal"):
        return None
    def value(r):
        s = r["summary"]
        for part in focus.split("."):
            s = s.get(part) if isinstance(s, dict) else None
        return s if isinstance(s, (int, float)) else -1
    best = max(rows, key=value)
    return f"Best by `{focus}`: **{best['variant']}** ({best['lang']}) = {_n(value(best))}"


def build_report(settings: Settings | None = None) -> Path:
    order = list(load_experiments())
    files = sorted(RESULTS_DIR.glob("*.json"), key=lambda p: order.index(p.stem) if p.stem in order else 999)
    out = [
        "# Experiment results",
        "",
        f"Generated by `python run.py report` on {utc_now()}. Every table compares variants of ONE pipeline",
        "component on the same 47 questions (39 answerable + 8 without an answer in the corpus);",
        "all other settings come from `configs/default.yaml`. Retrieval metrics are document-level and",
        "computed on the final Top-5 that would go to the LLM (see `src/evaluation/metrics.py`).",
        "Conclusions and the choice made for each experiment are in [DECISIONS.md](../DECISIONS.md).",
        "",
    ]
    for path in files:
        data = read_json(path)
        out += [f"## {data['experiment']}", "", data.get("description", ""), ""]
        out += _table(data)
        best = _best(data)
        if best:
            out += ["", best]
        out += ["", f"_Updated {data.get('updated_at')} on {data.get('machine', {}).get('platform', '?')}_", ""]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(out), encoding="utf-8")
    return REPORT
